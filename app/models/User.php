namespace App\Models;

use PDO;
use PDOException;

class User extends \App\Core\BaseModel {

    /**
     * Finds a user by their email address.
     * Could be adapted to find by username if you have a separate username field.
     *
     * @param string $email
     * @return array|false The user data as an associative array, or false if not found.
     */
    public function findByEmail(string $email): array|false {
        try {
            $stmt = $this->db->prepare("SELECT UserID, Email, PasswordHash, RoleID, FullName, IsActive FROM Users WHERE Email = :email LIMIT 1");
            $stmt->bindParam(':email', $email);
            $stmt->execute();
            return $stmt->fetch(PDO::FETCH_ASSOC);
        } catch (PDOException $e) {
            // Log error
            error_log("Error finding user by email: " . $e->getMessage());
            return false;
        }
    }

    /**
     * Finds a user by their UserID.
     * @param string $userId
     * @return array|false
     */
    public function findById(string $userId): array|false {
        try {
            // Assuming RoleName is needed from Roles table
            $sql = "SELECT u.UserID, u.Email, u.FullName, u.RoleID, u.IsActive, r.RoleName
                    FROM Users u
                    JOIN Roles r ON u.RoleID = r.RoleID
                    WHERE u.UserID = :userId LIMIT 1";
            $stmt = $this->db->prepare($sql);
            $stmt->bindParam(':userId', $userId, PDO::PARAM_STR); // Assuming UserID is UUID (string)
            $stmt->execute();
            return $stmt->fetch(PDO::FETCH_ASSOC);
        } catch (PDOException $e) {
            error_log("Error finding user by ID: " . $e->getMessage());
            return false;
        }
    }


    /**
     * Verifies a user's password against the stored hash.
     *
     * @param string $password The plain-text password to verify.
     * @param string $hashedPassword The stored hashed password.
     * @return bool True if the password matches, false otherwise.
     */
    public function verifyPassword(string $password, string $hashedPassword): bool {
        return password_verify($password, $hashedPassword);
    }

    /**
