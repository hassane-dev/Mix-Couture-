            // $userId = ... // generate UUID here if not auto-generated by DB

            // For simplicity, if your UserID is auto-increment integer:
            // $stmt = $this->db->prepare("INSERT INTO Users (FullName, Email, PasswordHash, RoleID, IsActive, CreatedAt, UpdatedAt) VALUES (:fullName, :email, :passwordHash, :roleId, TRUE, NOW(), NOW())");

            // If UserID is UUID and you need to generate it in PHP (example):
            $userId = $this->generateUuid(); // You'd need a UUID generation method

